// Copies the brand and panel fonts from @fontsource into public/fonts and writes their @font-face data, so neither the
// render nor the panel needs the internet. Run again only when a font or weight changes: node scripts/vendor-fonts.mjs
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { p } from "./lib/paths.mjs";

const SETS = [
  { pkg: "barlow-condensed", family: "Barlow Condensed", weights: [700, 800], render: true },
  { pkg: "barlow", family: "Barlow", weights: [500, 600, 700, 800], render: true },
  { pkg: "ibm-plex-mono", family: "IBM Plex Mono", weights: [500, 700], render: true },
  { pkg: "geist", family: "Geist", weights: [400, 500, 600] },
  { pkg: "geist-mono", family: "Geist Mono", weights: [400, 500] },
];
mkdirSync(p("public/fonts"), { recursive: true });
const faces = [];
for (const { pkg, family, weights, render } of SETS) for (const weight of weights) {
  const css = readFileSync(p(`node_modules/@fontsource/${pkg}/${weight}.css`), "utf8");
  for (const subset of ["latin", "latin-ext"]) {
    const block = css.split("@font-face").find((b) => b.includes(`${pkg}-${subset}-${weight}-normal.woff2`));
    const file = `${pkg}-${subset}-${weight}-normal.woff2`;
    copyFileSync(p(`node_modules/@fontsource/${pkg}/files/${file}`), p("public/fonts", file));
    faces.push({ family, weight: String(weight), file, unicodeRange: /unicode-range:\s*([^;]+);/.exec(block)[1].trim(), render: !!render });
  }
}
writeFileSync(p("src/theme/fonts.generated.ts"), `// Generated by scripts/vendor-fonts.mjs\nexport const fontFaces = ${JSON.stringify(faces.filter((f) => f.render).map(({ render: _render, ...f }) => f), null, 2)};\n`);
writeFileSync(p("studio/fonts.css"), faces.map((f) => `@font-face{font-family:'${f.family}';font-weight:${f.weight};font-style:normal;font-display:swap;src:url(/fonts/${f.file}) format('woff2');unicode-range:${f.unicodeRange}}`).join("\n") + "\n");
console.log(`${faces.length} yazı tipi dosyası → public/fonts`);
